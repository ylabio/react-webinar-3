/**
 * Хранилище состояния приложения
 */
class Store {
  constructor(initState = {}) {
    this.state = initState;
    this.listeners = []; // Слушатели изменений состояния
    this.itemCounter = Math.max(0, ...initState.list.map(item => item.code)) || 0;
  }

  /**
   * Подписка слушателя на изменения состояния
   * @param listener {Function}
   * @returns {Function} Функция отписки
   */
  subscribe(listener) {
    this.listeners.push(listener);
    // Возвращается функция для удаления добавленного слушателя
    return () => {
      this.listeners = this.listeners.filter(item => item !== listener);
    };
  }

  /**
   * Выбор состояния
   * @returns {Object}
   */
  getState() {
    return this.state;
  }

  /**
   * Установка состояния
   * @param newState {Object}
   */
  setState(newState) {
    this.state = newState;
    // Вызываем всех слушателей
    for (const listener of this.listeners) listener();
  }

  /**
   * Добавление новой записи
   */
  addItem() {
    this.setState({
      ...this.state,
      list: [...this.state.list, { code: ++this.itemCounter, title: 'Новая запись' }],
    });
  }

  /**
   * Удаление записи по коду
   * @param code
   */
  deleteItem(code) {
    this.setState({
      ...this.state,
      list: this.state.list.filter(item => item.code !== code),
    });
  }

  /**
   * Выделение записи по коду
   * @param code
   */
  selectItem(code, event) {
    if (event.target.tagName === 'BUTTON') return;

    const isMultiSelect = event.ctrlKey || event.metaKey;

    this.setState({
      ...this.state,
      list: this.state.list.map(item => {
        if (item.code !== code) {
          item.selected = isMultiSelect ? item.selected : false;
          return item;
        }

        item.selected = !item.selected;
        item.clickCount = item.selected ? (item.clickCount || 0) + 1 : item.clickCount;
        return item;
      }),
    });
  }
}

export default Store;

import { generateCode } from './utils';

/**
 * Хранилище состояния приложения
 */
class Store {
  constructor(initState = {}) {
    this.state = initState;
    this.listeners = []; // Слушатели изменений состояния
    this.cart = {};
  }

  getCart() {
    return this.cart;
  }

  addItemToCart(code) {
    const listElement = this.state.list.find(e => e.code === code);
    if (!listElement) {
      return;
    }

    const cartElement = {
      count: 1,
      ...listElement,
    };

    if (this.cart[code]) {
      cartElement.count = this.cart[code].count + 1;
    }

    this.cart[code] = cartElement;

    this.notifyListeners();
  }

  deleteItemFromCart(code) {
    const newCart = { ...this.cart };

    delete newCart[code];
    this.cart = newCart;

    this.notifyListeners();
  }

  getCartSize() {
    return Object.values(this.cart).length;
  }

  getCartSum() {
    return Object.values(this.cart).reduce((acc, curr) => acc + curr.price * curr.count, 0);
  }

  /**
   * Подписка слушателя на изменения состояния
   * @param listener {Function}
   * @returns {Function} Функция отписки
   */
  subscribe(listener) {
    this.listeners.push(listener);
    // Возвращается функция для удаления добавленного слушателя
    return () => {
      this.listeners = this.listeners.filter(item => item !== listener);
    };
  }

  notifyListeners() {
    this.listeners.forEach(listener => listener());
  }

  /**
   * Выбор состояния
   * @returns {Object}
   */
  getState() {
    return this.state;
  }

  /**
   * Установка состояния
   * @param newState {Object}
   */
  setState(newState) {
    this.state = newState;
    // Вызываем всех слушателей
    for (const listener of this.listeners) listener();
  }

  /**
   * Добавление новой записи
   */
  addItem() {
    this.setState({
      ...this.state,
      list: [...this.state.list, { code: generateCode(), title: 'Новая запись' }],
    });
  }

  /**
   * Удаление записи по коду
   * @param code
   */
  deleteItem(code) {
    this.setState({
      ...this.state,
      // Новый список, в котором не будет удаляемой записи
      list: this.state.list.filter(item => item.code !== code),
    });
  }

  /**
   * Выделение записи по коду
   * @param code
   */
  selectItem(code) {
    this.setState({
      ...this.state,
      list: this.state.list.map(item => {
        if (item.code === code) {
          // Смена выделения и подсчёт
          return {
            ...item,
            selected: !item.selected,
            count: item.selected ? item.count : item.count + 1 || 1,
          };
        }
        // Сброс выделения если выделена
        return item.selected ? { ...item, selected: false } : item;
      }),
    });
  }
}

export default Store;
